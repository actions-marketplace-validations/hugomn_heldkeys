//! SHA-256 and MD5, for matching files against published indicators of
//! compromise (`heldkeys incident`).
//!
//! Written out here rather than pulled in as dependencies: the two
//! functions are short, the inputs are a handful of files, and a tool that
//! checks for supply-chain compromises is better off with a small
//! dependency tree. Both are checked against the standard test vectors in
//! the tests below. MD5 is only here because OVHcloud published the
//! malicious builds of its CLI as MD5 hashes; nothing in heldkeys relies on
//! it for security.

use std::io::Read;
use std::path::Path;

/// Files bigger than this are not hashed: the indicators are small files
/// and command-line binaries.
pub const MAX_HASHED_BYTES: u64 = 512 * 1024 * 1024;

/// Lowercase hex SHA-256 of a file, or `None` if it is missing, not a
/// regular file, bigger than `MAX_HASHED_BYTES` or unreadable.
pub fn sha256_file(path: &Path) -> Option<String> {
    let mut h = Sha256::new();
    feed(path, |chunk| h.update(chunk))?;
    Some(hex(&h.finish()))
}

/// Lowercase hex MD5 of a file, with the same rules as `sha256_file`.
pub fn md5_file(path: &Path) -> Option<String> {
    let mut h = Md5::new();
    feed(path, |chunk| h.update(chunk))?;
    Some(hex(&h.finish()))
}

/// Lowercase hex SHA-256 of a byte string.
pub fn sha256(data: &[u8]) -> String {
    let mut h = Sha256::new();
    h.update(data);
    hex(&h.finish())
}

/// Lowercase hex MD5 of a byte string.
pub fn md5(data: &[u8]) -> String {
    let mut h = Md5::new();
    h.update(data);
    hex(&h.finish())
}

/// Reads `path` in chunks through `update`. A FIFO or device is refused
/// (it could block forever); so is a file over the size limit.
fn feed(path: &Path, mut update: impl FnMut(&[u8])) -> Option<()> {
    let meta = std::fs::metadata(path).ok()?;
    if !meta.is_file() || meta.len() > MAX_HASHED_BYTES {
        return None;
    }
    let mut file = crate::fsutil::open_regular(path).ok()?;
    let mut buf = vec![0u8; 64 * 1024];
    let mut read_total: u64 = 0;
    loop {
        let n = file.read(&mut buf).ok()?;
        if n == 0 {
            break;
        }
        read_total += n as u64;
        if read_total > MAX_HASHED_BYTES {
            return None;
        }
        update(&buf[..n]);
    }
    Some(())
}

pub fn hex(bytes: &[u8]) -> String {
    const DIGITS: &[u8; 16] = b"0123456789abcdef";
    let mut out = String::with_capacity(bytes.len() * 2);
    for b in bytes {
        out.push(DIGITS[(b >> 4) as usize] as char);
        out.push(DIGITS[(b & 0xf) as usize] as char);
    }
    out
}

/// Streaming SHA-256 (FIPS 180-4).
pub struct Sha256 {
    state: [u32; 8],
    block: [u8; 64],
    filled: usize,
    total: u64,
}

